-- 清掉「网盘搜索类型」里那个**从没被用户填过**的老默认值 `magnet,115`。
--
-- 背景（2026-10-12）：这个设置的语义变了 —— 从「全局指定搜哪些网盘类型」
-- 变成「**在自动推导的基础上额外追加**」。主类型现在由**这条订阅推送到的那个网盘**
-- 推导（见 tgsubscribe 的 effectiveCloudTypes：磁力 + 该网盘自己的分享链）。
--
-- 于是旧库里的 `magnet,115` 从「默认值」变成了「用户追加了一项 115」：
-- 一条指向夸克账号的订阅会去搜 `magnet,quark,115`，而 115 的分享链它根本转不了 ——
-- 表现是搜索结果里混进一屏「暂不支持投递」，用户从没碰过这个输入框却要为此买单。
--
-- 为什么可以安全地删：这一行要么是旧版本**自动写进去的默认值**，要么是用户手工
-- 填的同一个值。前者删掉正是本意；后者只会在「指向 115 账号的订阅」上少搜一遍 115 ——
-- 而那种订阅用自动推导照样会搜 115，结果完全一样。
-- 判据收紧到「值恰好等于旧默认值」，用户填过别的（比如加了 baidu）一律不动。
--
-- ⚠️ 时序是安全的：db.Migrate 在 settings.New 之前跑，加载时这行已经没了
-- （与 0024 删 tg_bot_token 同一条时序保证）。清空后的语义是「按目标网盘自动决定」，
-- 干净库本来就是这一档。
--
-- 顺带把代码里那个「只有库里写过才回写」的补丁（subscribe.go 的 UpdateConfig）
-- 一起留着：它防的是**将来**再有旧默认值被配置往返带回来。
DELETE FROM configs
 WHERE key = 'tg_websearch_cloud_types'
   AND replace(trim(value), ' ', '') = 'magnet,115';
