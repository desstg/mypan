-- 给「国产·无连字符」补上**漏掉的国内厂牌**（`MDCN` / `MDL` / `PMC` / `PM` / `MT` …）。
--
-- 背景：0037 加的那份厂牌表是**从用户磁盘上「国产AV」目录反推**的，而那批目录是他
-- **手工**改过名的（`MD-0292` / `MGL-0002` 那种带连字符的形态）—— 于是「只在无连字符
-- 形态里出现过」的厂牌被漏了。实测漏了 17 个，用户 2026-09-26 推的 `MDCN0001` /
-- `MDL0010-3` 就是栽在这上面（进了「未匹配」）。
--
-- 逐个拿全库 8442 个番号 + 18888 条磁链名验过：
--
--	MDCN 救 1    MDL 救 4    PMC 救 21   PM 救 6    MT 救 9    CP 救 3
--	MB / PMS / GDCM / CZ / MHG / PC / PMA / AAP / AAVV / ROOM / DOCUMENT 救 0（备用）
--
-- **抢走 0 个** —— 没有一个现在落在「有码/无码/欧美」的番号被它命中。
-- 尤其注意 `MT` 与日式的 `MTALL-*`：`MT` 后面要求**直接跟数字或分隔符**，
-- 而 `MTALL-028` 里 `MT` 后面是 `A`，所以匹配不上，`MTALL` 仍落在「有码」。
--
-- ## 为什么用 `replace()` 而不是重建数组
--
-- 这次改的是**一个字符串字段的内容**（往 pattern 里塞几个前缀），不是数组结构 ——
-- `replace()` 正合适，而且不需要碰下标（0038 那种重排才必须重建数组）。
--
-- ## 三条约束（与 0036 / 0037 同一套）
--
--  1. **按 pattern 的文本锚点匹配**，不按规则名（规则名用户可改）。
--  2. **找不到就什么都不做**（`instr(...) > 0`），因此幂等 —— 跑第二遍时锚点已变，
--     匹配不上。用户自己改过这条 pattern 的话也不硬塞。
--  3. 锚点选 `|DA)[-_]?` 这一段：**不含反斜杠**，绕开了这个项目里反复踩的
--     转义层数问题（0036 / 0037 都栽过：SQL 里写几个反斜杠才对得上，写错**不报错**、
--     只是规则永远不命中）。
--
-- ⚠️ **`value` 要写成 `configs.value`**：这条没有子查询，`replace(value, …)` 里的
-- `value` 就是 configs 那一列，没问题。但 `instr` 在 WHERE 里也一样直接引列名即可。
UPDATE configs
   SET value = replace(
           value,
           '|DA)[-_]?',
           '|DA|MDCN|MDL|PMC|MB|PMS|GDCM|PM|CZ|MHG|MT|PC|PMA|AAP|AAVV|CP)[-_]?'
       ),
       updated_at = CURRENT_TIMESTAMP
 WHERE key = 'mo_jav_rules'
   AND instr(value, '|DA)[-_]?') > 0
   AND instr(value, 'MDCN') = 0;
