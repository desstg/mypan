-- 番号识别放宽：连字符后可选一个字母（`MKD-S03` / `MKBD-S118`）。
--
-- 代码那边改了两处（`javrules.reCodeAlphaNum` 与 `reCodeExtract`），
-- 但**分类规则是存在库里的数据**，光改代码默认表对已存过规则的库不起作用 ——
-- 于是会出现最难查的那种不一致：`HasCode` 说「这是番号」（改名、认侧车都按番号走），
-- 分类却一个 pattern 都命中不了，最后落进兜底的「无匹配」。
--
-- 所以这里把库里那条**内容相同**的分类规则也改掉。
--
-- 三条设计约束：
--
--  1. **按 pattern 文本匹配，不按规则名**。规则名与目标目录名是用户可改的
--     （实测这台机器上就把「日本 / 日本AV」改成了「有码 / 有码」），
--     按名字找会一条都改不到，而且不报错。
--  2. **找不到就什么都不做**（`WHERE instr(...) > 0`）。用户可能已经把这条规则
--     删了、改成别的形态、或自己放宽过了 —— 那都不是错误，不该硬塞。
--     迁移因此天然幂等：跑第二遍时 `instr` 为 0。
--  3. **只替换这一处**。`replace()` 会替换整个 JSON 里的所有出现，而这个 pattern
--     字符串（`^[A-Za-z]{2,6}-\d{2,5}`）在规则表里只会出现在那一个 pattern 字段上 ——
--     includes 里全是片商名，junk_chars 是水印，都不长这样。
--
-- ⚠️ SQL 字面量里的反斜杠：JSON 里存的是转义后的 `\\d`，所以 SQL 里要写**两个**
-- 反斜杠才对得上（实测 `instr` 用两个才命中，用一个返回 0）。这是这条迁移最容易
-- 写错的地方 —— 写成一个的话整条 UPDATE 静默地不命中，看起来「迁移跑过了」。
UPDATE configs
SET value = replace(
        value,
        '^[A-Za-z]{2,6}-\\d{2,5}',
        '^[A-Za-z]{2,6}-[A-Za-z]?\\d{2,5}'
    )
WHERE key = 'mo_jav_rules'
  AND instr(value, '^[A-Za-z]{2,6}-\\d{2,5}') > 0;
