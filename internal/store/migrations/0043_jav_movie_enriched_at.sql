-- 「这部片的缺失字段已经被补过一轮」的时间戳。
--
-- 起因：用户要求「缺失的应该都补一下」—— 不只是简介，导演/时长/发行日期/类别这些
-- JAVDB 也常给空。补的动作是去别的站（jav321 / caribbeancom / javbus）问一圈，
-- 而这件事**必须能记账**：几千部片，不记就每轮都重打同一批，把站抓毛。
--
-- 为什么是一列时间戳而不是逐字段记账：这一版只想知道「问过没有」。逐字段的账
-- （哪一项从哪来）等真有多个来源、需要按字段挑选时再加 —— 现在就加只会是空壳。
--
-- 与 summary_source 的分工：那个记**简介**是哪来的（用户能在界面上看到来源），
-- 这个记**整轮补全**做过没有（纯内部记账，界面不显示）。
--
-- 空 = 还没补过。**补到也记、没补到也记**：那正是"下轮别再问"的意思。
-- 失败**不记**（失败多半是限流，记了就再也不会试）—— 与评论铺开同一条规矩。
