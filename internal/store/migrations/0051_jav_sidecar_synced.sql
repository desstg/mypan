-- 0051：「这部片的元数据已经回写过本地侧车」的时间戳。
--
-- 背景（2026-10-04）：侧车 json 是**推送那一刻的快照**（internal/jav/sidecar.go 的
-- writeSidecar 只读本地库、不抓上游），而写它的时候库里可能还没有演员 ——
-- 实测用户挂载目录里 76 份侧车有 **22 份 actors 为空**。库里后来补齐了，
-- 但侧车只写一次，**永远不会回写**。
--
-- 于是加一条后台循环（internal/jav/loops.go 的 sidecarSyncLoop）把库里**已有**的
-- 元数据回写进本地那份 json（并顺手补上同目录 nfo 里缺的元素）。它不打上游，
-- 所以没有限流/封号风险 —— 与「不在写侧车时回头抓上游」那条铁律不冲突。
--
-- **为什么必须单独一列，不能复用 enriched_at**：那个字段是
-- PendingSummaryMovieIDs（internal/store/jav_movie_repo.go）的候选判据，
-- 而那条链是**简介补缺**（要打 4~6 个外站）。抢过来会让简介补缺静默失效 ——
-- 补过的片不会再被挑中，界面上只表现为「简介一直空着」。
--
-- 空 = 还没回写过。**找到侧车就记**（改了没改都记：侧车里已经是新值就不必再走一遍）。
-- 「没找到侧车」分两种，见 sidecarSyncLoop 的注释：没推送过的记（将来推送时写的是
-- 当时的库，本来就是新的），推送过却没找到的**不记**（那份 json 还在网盘上，
-- 等同步下来再补）。
ALTER TABLE jav_movies ADD COLUMN sidecar_synced_at TIMESTAMP;

-- 0051 的第二列：详情回填**试过几次**。
--
-- 背景：详情回填（internal/jav/loops.go 的 detailBackfillLoop）的判据是
-- `raw_json` 为空，而**失败不记账**（判据本身就是「抓到了没有」）。那条设计对
-- 冷门片有个副作用：上游永远不收录它（番号对不上、或那部片根本不在 JAVDB），
-- 于是它**每一轮都会被重新挑出来、白打一次上游**。实测真库里那 12813 部有相当
-- 一部分是国产/素人片，属于这一类 —— 不封顶的话「补完」这件事永远不会发生。
--
-- 与 summary_attempts（0044）同一条思路：**既会重试、也有尽头**。
-- 到上限就不再进候选，所以「还剩 M 部」这个进度数是会真的归零的。
--
-- 成功不涨它（raw_json 一写进去，那部片就自动离开候选集了）；
-- 失败才 +1 —— 与简介补缺那边「失败不记账」不同，这里失败必须记，
-- 否则就是上面那个「永远重问」的毛病。
ALTER TABLE jav_movies ADD COLUMN detail_attempts INTEGER NOT NULL DEFAULT 0;
